import { mkdirSync, readFileSync, writeFileSync, existsSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const packet=dirname(fileURLToPath(import.meta.url));
const source='D:/VSCode Projects/cafecorner_nodebench/nodebench_ai4/NodeTrace';
const prior='D:/ProjectRecovery/nodetrace-entity-vite-consumer-20260905';
const target='D:/ProjectRecovery/nodetrace-entity-vite-final-consumer-20260905';
if(existsSync(target))throw Error('Retained target already exists');
mkdirSync(join(target,'src'),{recursive:true});
for(const f of ['index.html','src/main.tsx','vite.config.ts','tsconfig.json'])copyFileSync(join(prior,f),join(target,f));
const p=JSON.parse(readFileSync(join(prior,'package.json')));
p.scripts={build:'tsc --noEmit && vite build',dev:'vite --host 127.0.0.1'};
p.dependencies={react:'^19.0.0','react-dom':'^19.0.0'};
writeFileSync(join(target,'package.json'),JSON.stringify(p,null,2)+'\n');
const sha=b=>createHash('sha256').update(b).digest('hex');
const hostFiles=['index.html','src/main.tsx','vite.config.ts','tsconfig.json'];
const before=Object.fromEntries(hostFiles.map(f=>[f,sha(readFileSync(join(target,f)))]));
const generatorHash=sha(readFileSync(join(source,'bin/nodetrace.mjs')));
const run=spawnSync(process.execPath,[join(source,'bin/nodetrace.mjs'),'add','--target',target,'--framework','vite'],{cwd:source,encoding:'utf8',windowsHide:true,timeout:240000,maxBuffer:16*1024*1024});
writeFileSync(join(packet,'E6c-nodetrace-vite-final-install.log'),run.stdout+run.stderr);
const after=Object.fromEntries(hostFiles.map(f=>[f,sha(readFileSync(join(target,f)))]));
const receipt={source,target,generatorHash,exitCode:run.status,error:run.error?.message,before,after,hostUnchanged:JSON.stringify(before)===JSON.stringify(after),generatedEntry:readFileSync(join(target,'src/nodetrace-demo/main.tsx'),'utf8')};
writeFileSync(join(packet,'E6c-nodetrace-vite-final-install.json'),JSON.stringify(receipt,null,2));
console.log(JSON.stringify({target,exitCode:run.status,hostUnchanged:receipt.hostUnchanged}));
if(run.status!==0||!receipt.hostUnchanged)process.exitCode=1;
